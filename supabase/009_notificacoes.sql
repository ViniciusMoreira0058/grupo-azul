-- Guarda o celular de quem tocou em "Ativar notificações" e os avisos de cada pessoa.
-- Quem manda a notificação para o celular é a função "avisar" do Supabase (Edge Function).
-- Rode uma vez no SQL Editor (New query → colar → Run). Pode rodar de novo sem problema.
