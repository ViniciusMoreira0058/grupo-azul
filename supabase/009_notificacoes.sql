-- celulares e computadores que ativaram as notificações (ninguém lê direto, só pelas funções abaixo)
create table if not exists public.ga_push (
  id         bigint generated by default as identity primary key,
  equipe_id  uuid not null references public.ga_equipe(id) on delete cascade,
  endpoint   text not null unique,
  p256dh     text not null,
  auth       text not null,
  aparelho   text,
  criado_em  timestamptz not null default now()
);
create index if not exists ga_push_equipe_idx on public.ga_push (equipe_id);
alter table public.ga_push enable row level security;
revoke all on public.ga_push from anon, authenticated;

-- avisos: cada pessoa só vê os dela e só pode marcar como lido
create table if not exists public.ga_avisos (
  id         bigint generated by default as identity primary key,
  para       uuid not null references public.ga_equipe(id) on delete cascade,
  de         uuid references public.ga_equipe(id) on delete set null,
  titulo     text not null,
  corpo      text not null default '',
  pagina     text,
  lido       boolean not null default false,
  enviado_em timestamptz,
  criado_em  timestamptz not null default now()
);
create index if not exists ga_avisos_para_idx on public.ga_avisos (para, criado_em desc);
alter table public.ga_avisos enable row level security;
drop policy if exists ga_avisos_meus on public.ga_avisos;
create policy ga_avisos_meus on public.ga_avisos for select to authenticated using (para = public.ga_eu());
drop policy if exists ga_avisos_lido on public.ga_avisos;
create policy ga_avisos_lido on public.ga_avisos for update to authenticated using (para = public.ga_eu()) with check (para = public.ga_eu());
revoke all on public.ga_avisos from anon, authenticated;
grant select on public.ga_avisos to authenticated;
grant update (lido) on public.ga_avisos to authenticated;

-- ativou as notificações neste aparelho (se o aparelho era de outra pessoa, passa a ser de quem entrou)
create or replace function public.ga_push_salvar(p_endpoint text, p_p256dh text, p_auth text, p_aparelho text)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if public.ga_eu() is null then raise exception 'Sem acesso'; end if;
  if coalesce(p_endpoint, '') !~ '^https://' or coalesce(p_p256dh, '') = '' or coalesce(p_auth, '') = '' then raise exception 'Inscrição inválida'; end if;
  insert into public.ga_push (equipe_id, endpoint, p256dh, auth, aparelho)
  values (public.ga_eu(), p_endpoint, p_p256dh, p_auth, left(p_aparelho, 60))
  on conflict (endpoint) do update
     set equipe_id = excluded.equipe_id, p256dh = excluded.p256dh, auth = excluded.auth, aparelho = excluded.aparelho, criado_em = now();
end $$;

-- desligou neste aparelho ou saiu do app
create or replace function public.ga_push_apagar(p_endpoint text)
returns void language sql security definer set search_path = ''
as $$ delete from public.ga_push where endpoint = p_endpoint and equipe_id = public.ga_eu() $$;

-- grava os avisos e devolve os números (o app chama a função "avisar" com eles).
-- Escritório pode avisar qualquer pessoa ativa. Funcionário só avisa o escritório (perfis admin/fin).
-- [{"para": "uuid"} ou {"perfis": ["admin","fin"]}, "titulo": "...", "corpo": "...", "pagina": "os"}]
create or replace function public.ga_avisar(p_avisos jsonb)
returns bigint[] language plpgsql security definer set search_path = ''
as $$
declare eu uuid := public.ga_eu(); perfil text := public.ga_acesso(); a jsonb; alvo uuid; novo bigint; ids bigint[] := '{}';
begin
  if eu is null then raise exception 'Sem acesso'; end if;
  if jsonb_typeof(p_avisos) <> 'array' or jsonb_array_length(p_avisos) > 60 then raise exception 'Avisos inválidos'; end if;
  delete from public.ga_avisos where criado_em < now() - interval '60 days';  -- guarda só 2 meses
  for a in select * from jsonb_array_elements(p_avisos) loop
    if coalesce(trim(a->>'titulo'), '') = '' then continue; end if;
    for alvo in
      select e.id from public.ga_equipe e
       where e.ativo and e.id <> eu
         and ((perfil in ('admin','fin') and e.id::text = a->>'para')
              or (jsonb_typeof(a->'perfis') = 'array' and e.acesso in ('admin','fin')
                  and e.acesso in (select jsonb_array_elements_text(a->'perfis'))))
    loop
      insert into public.ga_avisos (para, de, titulo, corpo, pagina)
      values (alvo, eu, left(trim(a->>'titulo'), 120), left(coalesce(a->>'corpo', ''), 400),
              case when a->>'pagina' in ('obr','os','agd','lem','fin','dash') then a->>'pagina' end)
      returning id into novo;
      ids := ids || novo;
    end loop;
  end loop;
  return ids;
end $$;

revoke all on function public.ga_push_salvar(text,text,text,text), public.ga_push_apagar(text), public.ga_avisar(jsonb) from public, anon;
grant execute on function public.ga_push_salvar(text,text,text,text), public.ga_push_apagar(text), public.ga_avisar(jsonb) to authenticated;
