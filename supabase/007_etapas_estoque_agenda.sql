  nome       text not null,
  codigo     text,
  valor      numeric(12,2) not null default 0,
  entregue   date not null default (now() at time zone 'America/Sao_Paulo')::date,
  estado     text not null default 'Nova' check (estado in ('Nova','Boa','Precisa de reparo','Devolvida')),
  criado_em  timestamptz not null default now()
);
create index if not exists ga_ferramentas_equipe_idx on public.ga_ferramentas (equipe_id);

alter table public.ga_ferramentas enable row level security;
drop policy if exists ga_ferramentas_admin on public.ga_ferramentas;
create policy ga_ferramentas_admin on public.ga_ferramentas for all to authenticated
  using (public.ga_acesso() = 'admin') with check (public.ga_acesso() = 'admin');
grant select, insert, update, delete on public.ga_ferramentas to authenticated;

