-- ---------------------------------------------------------------------
-- 1. OBRA POR ETAPAS
--    As etapas continuam no campo etapas da obra, agora com os dias:
--    [{"t": "Passagem da tubulação", "dias": 6, "ok": false, "okEm": null}, ...]
--    O feedback do dia ganha o nível: bom, pouco ou parado.
-- ---------------------------------------------------------------------
alter table public.ga_feedbacks add column if not exists nivel text check (nivel in ('bom','pouco','parado'));
alter table public.ga_obras add column if not exists orcamento_id bigint references public.ga_orcamentos(id) on delete set null;

create or replace function public.ga_enviar_feedback_etapa(p_obra bigint, p_pct int, p_etapas jsonb, p_nivel text,
                                                           p_texto text, p_problema text, p_fotos text[])
returns void language plpgsql security definer set search_path = ''
as $$
declare hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  if public.ga_acesso() is null then raise exception 'Sem acesso'; end if;
  if not (public.ga_acesso() = 'admin' or public.ga_na_obra(p_obra)) then
    raise exception 'Você não está nessa obra';
  end if;
  if p_nivel not in ('bom','pouco','parado') then raise exception 'Nível inválido'; end if;
  insert into public.ga_feedbacks (obra_id, autor, data, pct, nivel, texto, problema, fotos)
  values (p_obra, public.ga_eu(), hoje, greatest(0, least(100, p_pct)), p_nivel, p_texto, nullif(p_problema, ''), coalesce(p_fotos, '{}'))
  on conflict (obra_id, autor, data) do update
     set pct = excluded.pct, nivel = excluded.nivel, texto = excluded.texto, problema = excluded.problema,
         fotos = public.ga_feedbacks.fotos || excluded.fotos;
  update public.ga_obras
     set pct = greatest(0, least(100, p_pct)), etapas = coalesce(p_etapas, etapas)
   where id = p_obra;
end $$;

-- ---------------------------------------------------------------------
-- 2. ESTOQUE (Administrador e Financeiro)
-- ---------------------------------------------------------------------
create table if not exists public.ga_estoque (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  categoria  text not null default 'Consumo',
  unidade    text not null default 'un.',
  qtd        numeric(12,2) not null default 0 check (qtd >= 0),
  minimo     numeric(12,2) not null default 0,
  custo      numeric(12,2) not null default 0,
  local      text,
  criado_em  timestamptz not null default now()
);
create table if not exists public.ga_estoque_mov (
  id         bigint generated by default as identity primary key,
  item_id    bigint not null references public.ga_estoque(id) on delete cascade,
  tipo       text not null check (tipo in ('entrada','saida')),
  qtd        numeric(12,2) not null check (qtd > 0),
  obra_id    bigint references public.ga_obras(id) on delete set null,
  data       date not null default (now() at time zone 'America/Sao_Paulo')::date,
  quem       uuid references public.ga_equipe(id) on delete set null default public.ga_eu(),
  obs        text,
  criado_em  timestamptz not null default now()
);
create index if not exists ga_estoque_mov_item_idx on public.ga_estoque_mov (item_id, data desc);

-- entrada ou baixa: grava a movimentação e acerta a quantidade de uma vez só
create or replace function public.ga_mover_estoque(p_item bigint, p_tipo text, p_qtd numeric, p_obra bigint, p_obs text)
returns void language plpgsql security definer set search_path = ''
as $$
declare tem numeric;
begin
  if coalesce(public.ga_acesso(), '') not in ('admin','fin') then raise exception 'Sem acesso'; end if;
  if p_tipo not in ('entrada','saida') or p_qtd is null or p_qtd <= 0 then raise exception 'Movimentação inválida'; end if;
  select qtd into tem from public.ga_estoque where id = p_item for update;
  if not found then raise exception 'Material não encontrado'; end if;
  if p_tipo = 'saida' and p_qtd > tem then raise exception 'Só tem % no estoque', trim_scale(tem); end if;
  update public.ga_estoque set qtd = qtd + case when p_tipo = 'entrada' then p_qtd else -p_qtd end where id = p_item;
  insert into public.ga_estoque_mov (item_id, tipo, qtd, obra_id, obs)
  values (p_item, p_tipo, p_qtd, case when p_tipo = 'saida' then p_obra end, nullif(p_obs, ''));
end $$;

alter table public.ga_estoque     enable row level security;
alter table public.ga_estoque_mov enable row level security;
drop policy if exists ga_estoque_escritorio on public.ga_estoque;
create policy ga_estoque_escritorio on public.ga_estoque for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_estoque_mov_ler on public.ga_estoque_mov;
create policy ga_estoque_mov_ler on public.ga_estoque_mov for select to authenticated
  using (public.ga_acesso() in ('admin','fin'));
grant select, insert, update, delete on public.ga_estoque to authenticated;
grant select on public.ga_estoque_mov to authenticated;

-- ---------------------------------------------------------------------
-- 3. AGENDA
--    Escritório vê e marca tudo. O funcionário só vê os compromissos em que
--    ele está E que o escritório marcou "Mostrar na agenda do funcionário".
-- ---------------------------------------------------------------------
create table if not exists public.ga_agenda (
  id         bigint generated by default as identity primary key,
  data       date not null,
  hora       text not null default '09:00',
  tipo       text not null default 'visita' check (tipo in ('visita','orc','manut','entrega','reuniao','confra')),
  titulo     text not null,
  cliente_id bigint references public.ga_clientes(id) on delete set null,
  quem       uuid[] not null default '{}',
  local      text,
  obs        text,
  feito      boolean not null default false,
  equipe_ve  boolean not null default false,
  criado_por uuid references public.ga_equipe(id) on delete set null default public.ga_eu(),
  criado_em  timestamptz not null default now()
);
create index if not exists ga_agenda_data_idx on public.ga_agenda (data);

alter table public.ga_agenda enable row level security;
drop policy if exists ga_agenda_escritorio on public.ga_agenda;
create policy ga_agenda_escritorio on public.ga_agenda for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_agenda_funcionario on public.ga_agenda;
create policy ga_agenda_funcionario on public.ga_agenda for select to authenticated
  using (equipe_ve and public.ga_eu() = any(quem));
grant select, insert, update, delete on public.ga_agenda to authenticated;

-- funcionário marca como feito um compromisso dele
create or replace function public.ga_agenda_feito(p_id bigint, p_feito boolean)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  update public.ga_agenda set feito = p_feito
   where id = p_id
     and (public.ga_acesso() in ('admin','fin') or (equipe_ve and public.ga_eu() = any(quem)));
  if not found then raise exception 'Compromisso não encontrado'; end if;
end $$;

-- nomes: o funcionário também vê o nome do cliente dos compromissos dele
create or replace function public.ga_nomes()
returns json language sql stable security definer set search_path = ''
as $$
  select case when public.ga_acesso() is null then null else json_build_object(
    'equipe', coalesce((select json_agg(json_build_object('id', e.id, 'nome', e.nome, 'funcao', e.funcao, 'ativo', e.ativo, 'acesso', e.acesso))
                          from public.ga_equipe e
                         where not e.oculto or e.user_id = auth.uid()), '[]'),
    'clientes', coalesce((select json_agg(json_build_object('id', c.id, 'nome', c.nome, 'cidade', c.cidade))
                            from public.ga_clientes c
                           where public.ga_acesso() in ('admin','fin')
                              or exists (select 1 from public.ga_obras o
                                          where o.cliente_id = c.id and public.ga_na_obra(o.id))
                              or exists (select 1 from public.ga_agenda a
                                          where a.cliente_id = c.id and a.equipe_ve and public.ga_eu() = any(a.quem))), '[]')
  ) end
$$;

