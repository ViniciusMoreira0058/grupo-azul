create table if not exists public.ga_os (
  id             bigint generated by default as identity primary key,
  cliente_id     bigint not null references public.ga_clientes(id) on delete cascade,
  tipo           text not null default 'vazamento' check (tipo in ('vazamento','desentup','troca','manut','instal','visita')),
  local          text,
  problema       text not null,
  contato        text,
  tecnico        uuid references public.ga_equipe(id) on delete set null,
  data           date not null,
  hora           text not null default '09:00',
  valor          numeric(12,2) not null default 0,
  status         text not null default 'Aberta' check (status in ('Aberta','Em andamento','Concluída','Cancelada')),
  -- preenchido ao fechar
  feito          text,
  materiais      jsonb not null default '[]',   -- [{"nome": "...", "qtd": 1, "v": 10.5, "item": id do estoque ou null}]
  mao            numeric(12,2) not null default 0,
  forma          text,
  pago           boolean not null default false,
  fotos_antes    text[] not null default '{}',
  fotos_depois   text[] not null default '{}',
  assinatura     text,                          -- imagem da assinatura (data:image/png)
  assin_nome     text,
  fechada_em     date,
  lancamento_id  bigint references public.ga_lancamentos(id) on delete set null,
  criado_por     uuid references public.ga_equipe(id) on delete set null default public.ga_eu(),
  criado_em      timestamptz not null default now()
);
create index if not exists ga_os_data_idx on public.ga_os (data);
create index if not exists ga_os_tecnico_idx on public.ga_os (tecnico);

alter table public.ga_os enable row level security;
drop policy if exists ga_os_escritorio on public.ga_os;
create policy ga_os_escritorio on public.ga_os for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_os_tecnico on public.ga_os;
create policy ga_os_tecnico on public.ga_os for select to authenticated
  using (tecnico = public.ga_eu());
grant select, insert, update, delete on public.ga_os to authenticated;

-- funcionário: começa o atendimento de uma OS dele
create or replace function public.ga_os_iniciar(p_id bigint)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  update public.ga_os set status = 'Em andamento'
   where id = p_id and status = 'Aberta'
     and (public.ga_acesso() in ('admin','fin') or tecnico = public.ga_eu());
  if not found then raise exception 'OS não encontrada ou já iniciada'; end if;
end $$;

-- fecha a OS: grava o que foi feito, dá baixa do material no estoque
-- e lança o valor no Financeiro como "a receber" (ou recebido, se o escritório marcar)
create or replace function public.ga_os_fechar(p_id bigint, p_feito text, p_materiais jsonb, p_mao numeric, p_forma text,
                                               p_fotos_antes text[], p_fotos_depois text[], p_assinatura text, p_assin_nome text, p_pago boolean)
returns void language plpgsql security definer set search_path = ''
as $$
declare o public.ga_os; m jsonb; total numeric := greatest(coalesce(p_mao, 0), 0); tem numeric; cli text; lid bigint;
        hoje date := (now() at time zone 'America/Sao_Paulo')::date; escritorio boolean := public.ga_acesso() in ('admin','fin');
begin
  select * into o from public.ga_os where id = p_id for update;
  if not found or not (escritorio or o.tecnico = public.ga_eu()) then raise exception 'OS não encontrada'; end if;
  if o.status not in ('Aberta','Em andamento') then raise exception 'Essa OS já foi fechada'; end if;
  if coalesce(trim(p_feito), '') = '' then raise exception 'Conte o que foi feito'; end if;
  if jsonb_typeof(coalesce(p_materiais, '[]')) <> 'array' then raise exception 'Materiais inválidos'; end if;
  for m in select * from jsonb_array_elements(coalesce(p_materiais, '[]')) loop
    if coalesce((m->>'qtd')::numeric, 0) <= 0 or coalesce((m->>'v')::numeric, 0) < 0 or coalesce(m->>'nome', '') = '' then
      raise exception 'Material inválido';
    end if;
    total := total + (m->>'qtd')::numeric * (m->>'v')::numeric;
    if m->>'item' is not null then
      select qtd into tem from public.ga_estoque where id = (m->>'item')::bigint for update;
      if not found then raise exception 'Material % não está no estoque', m->>'nome'; end if;
      if (m->>'qtd')::numeric > tem then raise exception 'No estoque só tem % de %', trim_scale(tem), m->>'nome'; end if;
      update public.ga_estoque set qtd = qtd - (m->>'qtd')::numeric where id = (m->>'item')::bigint;
      insert into public.ga_estoque_mov (item_id, tipo, qtd, obs)
      values ((m->>'item')::bigint, 'saida', (m->>'qtd')::numeric, 'OS-' || lpad(o.id::text, 4, '0'));
    end if;
  end loop;
  select nome into cli from public.ga_clientes where id = o.cliente_id;
  if total > 0 then
    insert into public.ga_lancamentos (tipo, data, descricao, categoria, quem, forma, valor, pago)
    values ('in', hoje,
            'OS-' || lpad(o.id::text, 4, '0') || ' · ' || case o.tipo when 'vazamento' then 'Vazamento' when 'desentup' then 'Desentupimento'
              when 'troca' then 'Troca de peça' when 'manut' then 'Manutenção' when 'instal' then 'Instalação' else 'Visita técnica' end || ' · ' || coalesce(cli, ''),
            case when o.tipo = 'visita' then 'Visita técnica' else 'Manutenção' end,
            coalesce(o.contato, cli), p_forma, round(total, 2), escritorio and coalesce(p_pago, false))
    returning id into lid;
  end if;
  update public.ga_os
     set status = 'Concluída', feito = trim(p_feito), materiais = coalesce(p_materiais, '[]'), mao = greatest(coalesce(p_mao, 0), 0),
         forma = p_forma, pago = escritorio and coalesce(p_pago, false), fotos_antes = coalesce(p_fotos_antes, '{}'),
         fotos_depois = coalesce(p_fotos_depois, '{}'), assinatura = nullif(p_assinatura, ''), assin_nome = nullif(trim(p_assin_nome), ''),
         fechada_em = hoje, lancamento_id = lid
   where id = p_id;
end $$;

-- funcionário: lista do estoque para escolher o material usado (sem custo, com preço sugerido)
create or replace function public.ga_estoque_lista()
returns json language sql stable security definer set search_path = ''
as $$
  select case when public.ga_acesso() is null then null else coalesce(
    (select json_agg(json_build_object('id', id, 'nome', nome, 'un', unidade, 'qtd', qtd, 'preco', round(custo * 1.5, 2)) order by nome)
       from public.ga_estoque where qtd > 0), '[]') end
$$;

-- nomes: o funcionário também vê o nome do cliente das OS dele
create or replace function public.ga_nomes()
returns json language sql stable security definer set search_path = ''
as $$
  select case when public.ga_acesso() is null then null else json_build_object(
    'equipe', coalesce((select json_agg(json_build_object('id', e.id, 'nome', e.nome, 'funcao', e.funcao, 'ativo', e.ativo, 'acesso', e.acesso))
                          from public.ga_equipe e
                         where not e.oculto or e.user_id = auth.uid()), '[]'),
    'clientes', coalesce((select json_agg(json_build_object('id', c.id, 'nome', c.nome, 'cidade', c.cidade))
                            from public.ga_clientes c
                           where public.ga_acesso() in ('admin','fin')
                              or exists (select 1 from public.ga_obras o
                                          where o.cliente_id = c.id and public.ga_na_obra(o.id))
                              or exists (select 1 from public.ga_agenda a
                                          where a.cliente_id = c.id and a.equipe_ve and public.ga_eu() = any(a.quem))
                              or exists (select 1 from public.ga_os s
                                          where s.cliente_id = c.id and s.tecnico = public.ga_eu())), '[]')
  ) end
$$;

revoke all on function public.ga_os_iniciar(bigint),
  public.ga_os_fechar(bigint,text,jsonb,numeric,text,text[],text[],text,text,boolean), public.ga_estoque_lista() from public, anon;
grant execute on function public.ga_os_iniciar(bigint),
  public.ga_os_fechar(bigint,text,jsonb,numeric,text,text[],text[],text,text,boolean), public.ga_estoque_lista() to authenticated;
