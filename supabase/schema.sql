-- ---------------------------------------------------------------------
-- 1. EQUIPE (dono, financeiro e funcionários de campo)
--    O dono/admin cadastra a pessoa com o e-mail. Quando ela cria a senha
--    no app com o mesmo e-mail, a conta de login é ligada a este cadastro.
-- ---------------------------------------------------------------------
create table if not exists public.ga_equipe (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid unique references auth.users(id) on delete set null,
  nome       text not null,
  funcao     text not null default 'Encanador',
  telefone   text,
  email      text,
  cpf        text,
  admissao   date,
  diaria     numeric(10,2) not null default 0,
  acesso     text not null default 'tec' check (acesso in ('admin','fin','tec')),
  ativo      boolean not null default true,
  dono       boolean not null default false,
  criado_em  timestamptz not null default now()
);
create unique index if not exists ga_equipe_email_idx on public.ga_equipe (lower(email)) where email is not null;

-- ---------------------------------------------------------------------
-- 2. CLIENTES
-- ---------------------------------------------------------------------
create table if not exists public.ga_clientes (
  id         bigint generated by default as identity primary key,
  nome       text not null,
  contato    text,
  telefone   text,
  cidade     text,
  servico    text,
  status     text not null default 'Aguardando aprovação'
             check (status in ('Aguardando aprovação','Planejamento','Em andamento','Concluída')),
  valor      numeric(12,2) not null default 0,
  criado_em  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 3. ORÇAMENTOS (itens em JSON: [["descrição", qtd, valor unitário], ...])
-- ---------------------------------------------------------------------
create table if not exists public.ga_orcamentos (
  id         bigint generated by default as identity primary key,
  numero     text not null unique,
  cliente_id bigint not null references public.ga_clientes(id) on delete cascade,
  data       date not null default (now() at time zone 'America/Sao_Paulo')::date,
  status     text not null default 'Rascunho' check (status in ('Rascunho','Enviado','Aprovado','Recusado')),
  titulo     text not null,
  itens      jsonb not null default '[]',
  criado_em  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 4. OBRAS (etapas em JSON: [{"t": "texto da etapa", "ok": false}, ...])
-- ---------------------------------------------------------------------
create table if not exists public.ga_obras (
  id          bigint generated by default as identity primary key,
  cliente_id  bigint not null references public.ga_clientes(id) on delete cascade,
  titulo      text not null,
  endereco    text,
  inicio      date not null,
  fim         date not null,
  responsavel uuid references public.ga_equipe(id) on delete set null,
  equipe      uuid[] not null default '{}',
  pct         smallint not null default 0 check (pct between 0 and 100),
  recado      text,
  etapas      jsonb not null default '[]',
  criado_em   timestamptz not null default now(),
  check (fim >= inicio)
);

-- ---------------------------------------------------------------------
-- 5. FEEDBACK DIÁRIO DA OBRA (1 por pessoa, por obra, por dia)
-- ---------------------------------------------------------------------
create table if not exists public.ga_feedbacks (
  id         bigint generated by default as identity primary key,
  obra_id    bigint not null references public.ga_obras(id) on delete cascade,
  autor      uuid references public.ga_equipe(id) on delete set null,
  data       date not null default (now() at time zone 'America/Sao_Paulo')::date,
  pct        smallint check (pct between 0 and 100),
  texto      text,
  problema   text,
  fotos      text[] not null default '{}',
  criado_em  timestamptz not null default now(),
  unique (obra_id, autor, data)
);

-- ---------------------------------------------------------------------
-- 6. FALTA DE PEÇA OU MATERIAL (pedido da equipe de campo)
-- ---------------------------------------------------------------------
create table if not exists public.ga_faltas (
  id         bigint generated by default as identity primary key,
  obra_id    bigint not null references public.ga_obras(id) on delete cascade,
  item       text not null,
  qtd        text,
  urgente    boolean not null default false,
  obs        text,
  autor      uuid references public.ga_equipe(id) on delete set null,
  data       date not null default (now() at time zone 'America/Sao_Paulo')::date,
  status     text not null default 'Aberto' check (status in ('Aberto','Comprado')),
  criado_em  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- 7. FINANCEIRO: entradas e saídas
-- ---------------------------------------------------------------------
create table if not exists public.ga_lancamentos (
  id          bigint generated by default as identity primary key,
  tipo        text not null check (tipo in ('in','out')),
  data        date not null,
  descricao   text not null,
  categoria   text,
  quem        text,
  obra_id     bigint references public.ga_obras(id) on delete set null,
  forma       text,
  valor       numeric(12,2) not null check (valor > 0),
  pago        boolean not null default true,
  comprovante text,
  criado_em   timestamptz not null default now()
);
create index if not exists ga_lancamentos_data_idx on public.ga_lancamentos (data);
create index if not exists ga_feedbacks_obra_idx on public.ga_feedbacks (obra_id, data desc);

-- ---------------------------------------------------------------------
-- 8. FUNÇÕES DE APOIO E REGRAS DE ACESSO
-- ---------------------------------------------------------------------
-- quem sou eu na equipe (só cadastro ativo)
create or replace function public.ga_eu()
returns uuid language sql stable security definer set search_path = ''
as $$ select id from public.ga_equipe where user_id = auth.uid() and ativo limit 1 $$;

-- meu perfil: 'admin', 'fin', 'tec' ou nulo (sem acesso)
create or replace function public.ga_acesso()
returns text language sql stable security definer set search_path = ''
as $$ select acesso from public.ga_equipe where user_id = auth.uid() and ativo limit 1 $$;

-- estou nessa obra (responsável ou equipe)?
create or replace function public.ga_na_obra(p_obra bigint)
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from public.ga_obras o
                  where o.id = p_obra
                    and (o.responsavel = public.ga_eu() or public.ga_eu() = any(o.equipe)))
$$;

-- liga a conta de login ao cadastro feito pelo escritório (mesmo e-mail)
-- e devolve o perfil. Nulo = e-mail não cadastrado.
create or replace function public.ga_vincular()
returns json language plpgsql security definer set search_path = ''
as $$
declare r public.ga_equipe; em text; achou boolean;
begin
  if auth.uid() is null then return null; end if;
  select * into r from public.ga_equipe where user_id = auth.uid();
  if not found then
    select email into em from auth.users where id = auth.uid();
    perform set_config('ga.vinculando', '1', true);
    update public.ga_equipe set user_id = auth.uid()
     where id = (select id from public.ga_equipe
                  where user_id is null and lower(email) = lower(em)
                  order by criado_em limit 1)
    returning * into r;
    achou := found;
    perform set_config('ga.vinculando', '', true);
    if not achou then return null; end if;
  end if;
  if not r.ativo then return json_build_object('inativo', true); end if;
  return json_build_object('id', r.id, 'nome', r.nome, 'funcao', r.funcao, 'acesso', r.acesso, 'dono', r.dono);
end $$;

-- usado na tela "Primeiro acesso" antes de criar a senha
create or replace function public.ga_email_cadastrado(p_email text)
returns boolean language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.ga_equipe where ativo and lower(email) = lower(trim(p_email))) $$;

-- nomes da equipe e dos clientes que a pessoa pode ver (sem CPF, valores etc.)
create or replace function public.ga_nomes()
returns json language sql stable security definer set search_path = ''
as $$
  select case when public.ga_acesso() is null then null else json_build_object(
    'equipe', coalesce((select json_agg(json_build_object('id', e.id, 'nome', e.nome, 'funcao', e.funcao, 'ativo', e.ativo))
                          from public.ga_equipe e), '[]'),
    'clientes', coalesce((select json_agg(json_build_object('id', c.id, 'nome', c.nome, 'cidade', c.cidade))
                            from public.ga_clientes c
                           where public.ga_acesso() in ('admin','fin')
                              or exists (select 1 from public.ga_obras o
                                          where o.cliente_id = c.id and public.ga_na_obra(o.id))), '[]')
  ) end
$$;

-- feedback do dia: grava (ou atualiza o de hoje) e atualiza o andamento da obra
create or replace function public.ga_enviar_feedback(p_obra bigint, p_pct int, p_etapas jsonb,
                                                     p_texto text, p_problema text, p_fotos text[])
returns void language plpgsql security definer set search_path = ''
as $$
declare hoje date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  if public.ga_acesso() is null then raise exception 'Sem acesso'; end if;
  if not (public.ga_acesso() = 'admin' or public.ga_na_obra(p_obra)) then
    raise exception 'Você não está nessa obra';
  end if;
  insert into public.ga_feedbacks (obra_id, autor, data, pct, texto, problema, fotos)
  values (p_obra, public.ga_eu(), hoje, greatest(0, least(100, p_pct)), p_texto, nullif(p_problema, ''), coalesce(p_fotos, '{}'))
  on conflict (obra_id, autor, data) do update
     set pct = excluded.pct, texto = excluded.texto, problema = excluded.problema,
         fotos = public.ga_feedbacks.fotos || excluded.fotos;
  update public.ga_obras
     set pct = greatest(0, least(100, p_pct)), etapas = coalesce(p_etapas, etapas)
   where id = p_obra;
end $$;

-- marcar etapas feitas direto no cartão da obra
create or replace function public.ga_atualizar_etapas(p_obra bigint, p_etapas jsonb)
returns void language plpgsql security definer set search_path = ''
as $$
begin
  if not (public.ga_acesso() = 'admin' or public.ga_na_obra(p_obra)) then
    raise exception 'Você não está nessa obra';
  end if;
  update public.ga_obras set etapas = p_etapas where id = p_obra;
end $$;

-- protege a conta do dono e a ligação com o login
create or replace function public.ga_proteger_equipe()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  if tg_op = 'DELETE' then
    if old.dono then raise exception 'A conta do dono não pode ser excluída'; end if;
    return old;
  end if;
  if tg_op = 'INSERT' then
    if new.dono and exists (select 1 from public.ga_equipe where dono) then
      raise exception 'Já existe um dono cadastrado';
    end if;
    new.email := lower(trim(new.email));
    if coalesce(current_setting('ga.vinculando', true), '') <> '1' then new.user_id := null; end if;
    return new;
  end if;
  -- UPDATE
  if old.dono and (not new.ativo or new.acesso <> 'admin' or not new.dono) then
    raise exception 'A conta do dono fica sempre ativa e como administrador';
  end if;
  if new.dono and not old.dono then raise exception 'Só existe um dono'; end if;
  new.email := lower(trim(new.email));
  -- trocou o e-mail: a pessoa cria a senha de novo com o e-mail novo
  if new.email is distinct from old.email then new.user_id := null;
  elsif new.user_id is distinct from old.user_id
        and new.user_id is not null
        and coalesce(current_setting('ga.vinculando', true), '') <> '1' then
    raise exception 'O login só é ligado pelo próprio funcionário';
  end if;
  return new;
end $$;
drop trigger if exists ga_proteger_equipe on public.ga_equipe;
create trigger ga_proteger_equipe before insert or update or delete on public.ga_equipe
  for each row execute function public.ga_proteger_equipe();

-- permissões das funções
revoke all on function public.ga_eu(), public.ga_acesso(), public.ga_na_obra(bigint), public.ga_vincular(),
  public.ga_nomes(), public.ga_enviar_feedback(bigint,int,jsonb,text,text,text[]),
  public.ga_atualizar_etapas(bigint,jsonb), public.ga_email_cadastrado(text) from public, anon;
grant execute on function public.ga_eu(), public.ga_acesso(), public.ga_na_obra(bigint), public.ga_vincular(),
  public.ga_nomes(), public.ga_enviar_feedback(bigint,int,jsonb,text,text,text[]),
  public.ga_atualizar_etapas(bigint,jsonb), public.ga_email_cadastrado(text) to authenticated;
grant execute on function public.ga_email_cadastrado(text) to anon;

