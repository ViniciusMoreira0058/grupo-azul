drop policy if exists ga_equipe_ler on public.ga_equipe;
create policy ga_equipe_ler on public.ga_equipe for select to authenticated
  using (public.ga_acesso() = 'admin' or user_id = auth.uid());
drop policy if exists ga_equipe_admin on public.ga_equipe;
create policy ga_equipe_admin on public.ga_equipe for all to authenticated
  using (public.ga_acesso() = 'admin') with check (public.ga_acesso() = 'admin');

-- clientes, orçamentos e financeiro: dono/admin e financeiro
drop policy if exists ga_clientes_escritorio on public.ga_clientes;
create policy ga_clientes_escritorio on public.ga_clientes for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_orcamentos_escritorio on public.ga_orcamentos;
create policy ga_orcamentos_escritorio on public.ga_orcamentos for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_lancamentos_escritorio on public.ga_lancamentos;
create policy ga_lancamentos_escritorio on public.ga_lancamentos for all to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));

-- obras: escritório vê todas; funcionário só as dele. Só o admin cria e edita.
drop policy if exists ga_obras_ler on public.ga_obras;
create policy ga_obras_ler on public.ga_obras for select to authenticated
  using (public.ga_acesso() in ('admin','fin') or responsavel = public.ga_eu() or public.ga_eu() = any(equipe));
drop policy if exists ga_obras_admin on public.ga_obras;
create policy ga_obras_admin on public.ga_obras for all to authenticated
  using (public.ga_acesso() = 'admin') with check (public.ga_acesso() = 'admin');

-- feedbacks: leitura igual às obras; gravação pela função ga_enviar_feedback
drop policy if exists ga_feedbacks_ler on public.ga_feedbacks;
create policy ga_feedbacks_ler on public.ga_feedbacks for select to authenticated
  using (public.ga_acesso() in ('admin','fin') or public.ga_na_obra(obra_id));
drop policy if exists ga_feedbacks_admin on public.ga_feedbacks;
create policy ga_feedbacks_admin on public.ga_feedbacks for all to authenticated
  using (public.ga_acesso() = 'admin') with check (public.ga_acesso() = 'admin');

-- faltas de material: funcionário pede nas obras dele; escritório marca como comprado
drop policy if exists ga_faltas_ler on public.ga_faltas;
create policy ga_faltas_ler on public.ga_faltas for select to authenticated
  using (public.ga_acesso() in ('admin','fin') or public.ga_na_obra(obra_id));
drop policy if exists ga_faltas_pedir on public.ga_faltas;
create policy ga_faltas_pedir on public.ga_faltas for insert to authenticated
  with check (public.ga_acesso() = 'admin' or (public.ga_na_obra(obra_id) and autor = public.ga_eu()));
drop policy if exists ga_faltas_escritorio on public.ga_faltas;
create policy ga_faltas_escritorio on public.ga_faltas for update to authenticated
  using (public.ga_acesso() in ('admin','fin')) with check (public.ga_acesso() in ('admin','fin'));
drop policy if exists ga_faltas_apagar on public.ga_faltas;
create policy ga_faltas_apagar on public.ga_faltas for delete to authenticated
  using (public.ga_acesso() = 'admin');

